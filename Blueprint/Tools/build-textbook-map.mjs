// Generate the Blueprint textbook coverage map.
//
// Every statement card under `Blueprint/Chapters/` that carries a structured
// source annotation cites a document and a page (or a page range, a section, an
// equation). This script collects those citations from the chapter sources and
// places every Evans citation into the recorded outline below for the adopted
// 2010 second edition of Evans, *Partial Differential Equations*. Section starts
// were checked against the reference copy obtained from Caltech Library. The
// result is a JSON string literal in
// `Blueprint/Generated/TextbookMapData.lean`, decoded at elaboration time by
// `Blueprint.Commands.TextbookMap`, exactly as the computation ledger is
// generated by `Blueprint/Tools/build-cas-ledger.mjs`. `Blueprint/Tools/build.sh`
// regenerates the file before `lake build Blueprint`; `--check` reports whether
// the committed copy is stale without rewriting it.
//
// The map counts statements, not pages of prose: a section is "covered" when
// at least one card cites a page inside it. A card citing a page range is
// placed in the section that contains the first cited page.

