const EVANS_ID = "evans-pde";

function walk(root) {
  const files = [];
  const pending = [root];
  while (pending.length > 0) {
    const current = pending.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      if (entry.name.startsWith(".")) continue;
      const target = path.join(current, entry.name);
      if (entry.isDirectory()) {
        pending.push(target);
      } else if (entry.isFile() && entry.name.endsWith(".lean")) {
        files.push(target);
      }
    }
  }
  return files.sort();
}

// Titles of the registered source documents, read from the `:::source_document`
// directives of the Overview so the map never carries a second copy of them.
function readDocumentTitles() {
  const titles = new Map();
  const source = fs.readFileSync(overviewPath, "utf8");
  const pattern = /:::source_document\s+"([^"]+)"\s*\n%%%\s*\ntitle\s*:=\s*"((?:[^"\\]|\\[\s\S])*)"/g;
  for (const match of source.matchAll(pattern)) {
    const title = match[2].replace(/\\\s*\n\s*/g, "").replace(/\\"/g, "\"");
    titles.set(match[1], title);
  }
  return titles;
}

const directivePattern =
  /^:::(theorem|definition|lemma_|proposition|corollary)\s+"([^"]+)"/;

// Read locators from each span separately. Braces in quoted strings and nested
// text/PDF records must not split a span or contribute a locator of their own.
function spanLocations(metadata, context) {
  const start = /\bspans\s*:=\s*#\[/.exec(metadata);
  if (!start) throw new Error(`${context}: source has no spans array.`);
  const tokens = metadata.slice(start.index + start[0].length).matchAll(
    /\b(page|citation)\s*:=\s*("(?:\\.|[^"\\])*")|"(?:\\.|[^"\\])*"|[{}[\]]/g,
  );
  const spans = [];
  let depth = 0;
  let current;
  let closed = false;
  for (const token of tokens) {
    if (token[0] === "]" && depth === 0) {
      closed = true;
      break;
    }
    if (token[0] === "{") {
      if (depth === 0) current = { page: null, citation: null };
      depth += 1;
    } else if (token[0] === "}") {
      depth -= 1;
      if (depth === 0) {
        if (![current.page, current.citation].some((value) => value?.trim())) {
          throw new Error(`${context}: each source span needs a page or citation.`);
        }
        spans.push(current);
      }
    } else if (depth === 1 && token[1]) {
      current[token[1]] = JSON.parse(token[2]);
    }
  }
  if (!closed || spans.length === 0) {
    throw new Error(`${context}: source needs a nonempty, closed spans array.`);
  }
  return spans;
}

// Scan one chapter module for statement directives followed by a metadata block
// with a structured source reference. A span may cite a page, a section, or both.
function scanFile(relativePath, source) {
  const lines = source.split("\n");
  const citations = [];
  let current = null;
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const directive = directivePattern.exec(line);
    if (directive) {
      current = {
        kind: directive[1] === "lemma_" ? "lemma" : directive[1],
        label: directive[2],
        line: index + 1,
      };
      continue;
    }
    if (/^:::proof\b/.test(line) || /^:::group\b/.test(line)) {
      current = null;
      continue;
    }
    if (!current) continue;
    const document = /^\s*document\s*:=\s*"([^"]+)"/.exec(line);
    if (!document) continue;
    let cursor = index + 1;
    while (cursor < lines.length && !/^%%%/.test(lines[cursor])) {
      cursor += 1;
    }
    const spans = spanLocations(
      lines.slice(index + 1, cursor).join("\n"), `${relativePath}:${current.line}`,
    );
    for (const span of spans) {
      citations.push({
        label: current.label,
        kind: current.kind,
        document: document[1],
        ...span,
        file: relativePath,
        line: current.line,
      });
    }
  }
  return citations;
}

function parsePageStart(page) {
  if (page === null) return null;
  const match = /^([0-9]+)(?:-([0-9]+))?$/.exec(page.trim());
  if (!match) return null;
  return {
    start: Number.parseInt(match[1], 10),
    end: match[2] ? Number.parseInt(match[2], 10) : Number.parseInt(match[1], 10),
  };
}

function cardEntry(citation) {
  return {
    label: citation.label,
    kind: citation.kind,
    page: citation.page,
    citation: citation.citation,
    file: citation.file,
    line: citation.line,
  };
}

function compareCards(a, b) {
  const pa = parsePageStart(a.page);
  const pb = parsePageStart(b.page);
  if (pa && pb && pa.start !== pb.start) return pa.start - pb.start;
  if (pa && pb && pa.end !== pb.end) return pa.end - pb.end;
  return a.label < b.label ? -1 : a.label > b.label ? 1 : 0;
}

// Build the Evans table of contents with resolved page ranges.
function buildEvansUnits() {
  const units = [];
  for (let c = 0; c < EVANS_CHAPTERS.length; c += 1) {
    const chapter = EVANS_CHAPTERS[c];
    const next = EVANS_CHAPTERS[c + 1];
    const chapterEnd = chapter.end ?? (next ? next.start - 1 : chapter.start);
    const sections = [];
    for (let s = 0; s < chapter.sections.length; s += 1) {
      const [number, title, start, role = "section", approx] = chapter.sections[s];
      const following = chapter.sections[s + 1];
      const end = following ? following[2] - 1 : chapterEnd;
      if (end < start) {
        throw new Error(`Evans section ${number} has an empty page range ${start}-${end}.`);
      }
      sections.push({
        number,
        title,
        pageStart: start,
        pageEnd: end,
        approx: approx === "approx",
        role,
        cards: [],
      });
    }
    units.push({
      number: chapter.number,
      title: chapter.title,
      pageStart: chapter.start,
      pageEnd: chapterEnd,
      approx: chapter.approx === true,
      sections,
    });
  }
  return units;
}

const documentTitles = readDocumentTitles();
const citations = [];
for (const file of walk(chaptersRoot)) {
  const relativePath = path.relative(repoRoot, file).split(path.sep).join("/");
  citations.push(...scanFile(relativePath, fs.readFileSync(file, "utf8")));
}

if (citations.length === 0) {
  throw new Error("No structured source citations were found under Blueprint/Chapters.");
}

const documentIds = [...new Set(citations.map((citation) => citation.document))].sort((a, b) =>
  a === EVANS_ID ? -1 : b === EVANS_ID ? 1 : a < b ? -1 : a > b ? 1 : 0
);

const documents = [];
for (const id of documentIds) {
  const cited = citations.filter((citation) => citation.document === id);
  const title = documentTitles.get(id);
  if (!title) {
    throw new Error(`Source document ${id} is cited but not registered in Blueprint/Chapters/Overview.lean.`);
  }
  if (id === EVANS_ID) {
    const units = buildEvansUnits();
    const unplaced = [];
    for (const citation of cited) {
      const pages = parsePageStart(citation.page);
      let placed = false;
      if (pages) {
        for (const unit of units) {
          for (const section of unit.sections) {
            if (pages.start >= section.pageStart && pages.start <= section.pageEnd) {
              section.cards.push(cardEntry(citation));
              placed = true;
              break;
            }
          }
          if (placed) break;
        }
      }
      if (!placed) unplaced.push(cardEntry(citation));
    }
    for (const unit of units) {
      for (const section of unit.sections) section.cards.sort(compareCards);
    }
    unplaced.sort(compareCards);
    documents.push({
      id,
      title,
      layout: "toc",
      citations: cited.length,
      cards: new Set(cited.map((citation) => citation.label)).size,
      units,
      unplaced,
      locations: [],
    });
  } else {
    const byLocation = new Map();
    for (const citation of cited) {
      const key = JSON.stringify([citation.page, citation.citation]);
      if (!byLocation.has(key)) byLocation.set(key, []);
      byLocation.get(key).push(cardEntry(citation));
    }
    const locations = [...byLocation.entries()]
      .map(([key, cards]) => {
        const [page, citation] = JSON.parse(key);
        return { page, citation, cards: cards.sort(compareCards) };
      })
      .sort((a, b) => {
        const pa = parsePageStart(a.page);
        const pb = parsePageStart(b.page);
        if (pa && pb) {
          const order = pa.start - pb.start || pa.end - pb.end;
          if (order) return order;
        } else if (pa) return -1;
        else if (pb) return 1;
        const ka = `${a.page ?? ""}\n${a.citation ?? ""}`;
        const kb = `${b.page ?? ""}\n${b.citation ?? ""}`;
        return ka < kb ? -1 : ka > kb ? 1 : 0;
      });
    documents.push({
      id,
      title,
      layout: "list",
      citations: cited.length,
      cards: new Set(cited.map((citation) => citation.label)).size,
      units: [],
      unplaced: [],
      locations,
    });
  }
}

const evans = documents.find((document) => document.id === EVANS_ID);
const evansSections = evans ? evans.units.flatMap((unit) => unit.sections) : [];
const resultSections = evansSections.filter((section) => section.role === "section");
const coveredSections = resultSections.filter((section) => section.cards.length > 0);

const map = {
  schemaVersion: 2,
  generator: "Blueprint/Tools/build-textbook-map.mjs",
  sourceRoot: "Blueprint/Chapters",
  summary: {
    citations: citations.length,
    cards: new Set(citations.map((citation) => citation.label)).size,
    documents: documents.length,
    evansSections: resultSections.length,
    evansCoveredSections: coveredSections.length,
    evansUnplaced: evans ? evans.unplaced.length : 0,
  },
  documents,
};

const json = JSON.stringify(map, null, 2);
const delimiter = "####";
if (json.includes(`"${delimiter}`)) {
  throw new Error("Textbook map JSON contains the raw string terminator sequence.");
}

