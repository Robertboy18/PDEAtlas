if (jsonPath) {
  fs.mkdirSync(path.dirname(path.resolve(jsonPath)), { recursive: true });
  fs.writeFileSync(jsonPath, json + "\n");
}

const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
const summaryText =
  `${map.summary.citations} citations on ${map.summary.cards} cards; `
  + `${map.summary.evansCoveredSections}/${map.summary.evansSections} Evans sections covered, `
  + `${map.summary.evansUnplaced} Evans citations unplaced.`;
if (checkOnly) {
  if (existing !== leanSource) {
    console.error(
      `Textbook map is stale: run node Blueprint/Tools/build-textbook-map.mjs to regenerate ${path.relative(repoRoot, outputPath)}.`
    );
    process.exit(1);
  }
  console.log(`Textbook map is current: ${summaryText}`);
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  if (existing !== leanSource) fs.writeFileSync(outputPath, leanSource);
  console.log(`Textbook map: ${summaryText} Written to ${path.relative(repoRoot, outputPath)}.`);
}
